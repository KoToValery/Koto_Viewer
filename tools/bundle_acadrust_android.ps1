param(
    [string]$SdkRoot,
    [string]$NdkVersion = '28.2.13676358'
)
$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
if (-not $SdkRoot) {
    $line = Get-Content "$repoRoot/android/local.properties" | Where-Object { $_ -like 'sdk.dir=*' } | Select-Object -First 1
    if (-not $line) { throw 'Configure sdk.dir or pass -SdkRoot.' }
    $SdkRoot = $line.Substring(8).Replace('\\', '\').Replace('\:', ':')
}
$strip = "$SdkRoot/ndk/$NdkVersion/toolchains/llvm/prebuilt/windows-x86_64/bin/llvm-strip.exe"
if (-not (Test-Path $strip)) { throw 'The NDK llvm-strip tool is required.' }
$bundle = "$repoRoot/src/acadrust_converter/prebuilt/android"
$manifest = @('# Generated by tools/bundle_acadrust_android.ps1. Commit binaries and manifest together.')
foreach ($abi in @('arm64-v8a', 'armeabi-v7a', 'x86_64')) {
    $source = "$repoRoot/build/acadrust/android-cmake/$abi/libkoto_acadrust.so"
    if (-not (Test-Path $source)) { throw "Build the native $abi library first." }
    New-Item -ItemType Directory -Force -Path "$bundle/$abi" | Out-Null
    $target = "$bundle/$abi/libkoto_acadrust.so"
    Copy-Item -LiteralPath $source -Destination $target
    & $strip --strip-unneeded $target
    if ($LASTEXITCODE -ne 0) { throw "Cannot strip $abi library." }
    $hash = (Get-FileHash -LiteralPath $target -Algorithm SHA256).Hash.ToLowerInvariant()
    $manifest += "set(KOTO_ACADRUST_SHA256_$abi `"$hash`")"
}
$inputs = @('Cargo.toml', 'Cargo.lock', 'src/lib.rs', 'src/ffi.rs', 'src/reader.rs', 'src/writer.rs', '../../android/app/src/main/cpp/acadrust_jni.c')
$manifest += "set(KOTO_ACADRUST_NATIVE_INPUTS `"$($inputs -join ';')`")"
$index = 0
foreach ($input in $inputs) {
    $content = [IO.File]::ReadAllText("$repoRoot/src/acadrust_converter/$input").Replace("`r`n", "`n")
    $sha = [Security.Cryptography.SHA256]::Create()
    try { $hash = [BitConverter]::ToString($sha.ComputeHash([Text.Encoding]::UTF8.GetBytes($content))).Replace('-', '').ToLowerInvariant() }
    finally { $sha.Dispose() }
    $manifest += "set(KOTO_ACADRUST_SOURCE_$index `"$hash`")"
    $index++
}
Set-Content -LiteralPath "$bundle/manifest.cmake" -Value $manifest -Encoding utf8
Write-Output 'Bundled Android DWG reader/writer: arm64-v8a, armeabi-v7a, x86_64. Commit prebuilt/android together with the source changes.'
